import { GoogleGenAI, Type } from "@google/genai";

const ai = new GoogleGenAI({ apiKey: process.env.GEMINI_API_KEY });

export interface ValuationResult {
  estimatedValue: number;
  marketRange: {
    low: number;
    high: number;
  };
  confidence: number;
  analysis: string;
}

export function getFallbackValuation(
  make: string,
  model: string,
  year: number,
  mileage: number,
  condition: string
): ValuationResult {
  // Base values for popular brands in Pakistan in PKR
  let baseValue = 3500000; // default 35 Lacs
  
  const lowerMake = make.toLowerCase();
  const lowerModel = model.toLowerCase();
  
  if (lowerMake.includes('toyota')) {
    if (lowerModel.includes('land cruiser') || lowerModel.includes('prado')) baseValue = 25000000;
    else if (lowerModel.includes('fortuner')) baseValue = 12000000;
    else if (lowerModel.includes('corolla') || lowerModel.includes('yaris') || lowerModel.includes('yaris')) baseValue = 5500000;
    else baseValue = 6000000;
  } else if (lowerMake.includes('honda')) {
    if (lowerModel.includes('civic')) baseValue = 6800000;
    else if (lowerModel.includes('city')) baseValue = 4200000;
    else if (lowerModel.includes('hr-v') || lowerModel.includes('hrv') || lowerModel.includes('br-v')) baseValue = 6500000;
    else baseValue = 5000000;
  } else if (lowerMake.includes('suzuki')) {
    if (lowerModel.includes('alto')) baseValue = 2605000;
    else if (lowerModel.includes('swift')) baseValue = 4000000;
    else if (lowerModel.includes('cultus') || lowerModel.includes('wagon r')) baseValue = 3000000;
    else baseValue = 2800000;
  } else if (lowerMake.includes('audi') || lowerMake.includes('bmw') || lowerMake.includes('mercedes') || lowerMake.includes('porsche')) {
    baseValue = 18000000;
  } else if (lowerMake.includes('kia') || lowerMake.includes('hyundai')) {
    if (lowerModel.includes('sportage') || lowerModel.includes('tucson')) baseValue = 7500000;
    else baseValue = 4500000;
  }
  
  // Year depreciation/inflation adjustment
  const currentYear = 2024;
  const age = Math.max(0, currentYear - year);
  const ageFactor = Math.max(0.4, 1 - (age * 0.04));
  
  // Mileage factor: up to 20% depreciation
  const mileageFactor = Math.max(0.8, 1 - (mileage / 100000) * 0.05);
  
  // Condition factor
  let conditionFactor = 1.0;
  if (condition === 'excellent') conditionFactor = 1.05;
  else if (condition === 'good') conditionFactor = 0.95;
  else if (condition === 'fair') conditionFactor = 0.82;
  
  let estimatedValue = Math.round(baseValue * ageFactor * mileageFactor * conditionFactor);
  // Round to nearest 10,000 for clean look
  estimatedValue = Math.round(estimatedValue / 10000) * 10000;
  if (estimatedValue < 500000) estimatedValue = 500000; // minimum price fallback
  
  const low = Math.round((estimatedValue * 0.91) / 10000) * 10000;
  const high = Math.round((estimatedValue * 1.07) / 10000) * 10000;
  
  const confidence = 0.85;
  const analysis = `This valuation was generated by our local offline pricing engine (active to bypass API quota limits). A ${year} ${make} ${model} in Pakistan continues to show resilient demand despite market corrections. ${condition === 'excellent' ? 'Its pristine condition qualifies it for a premium above standard market resale curves.' : 'Given its mileage and status, it lies securely within the sweet spot of active buyer demand.'}`;
  
  return {
    estimatedValue,
    marketRange: { low, high },
    confidence,
    analysis
  };
}

export async function getVehicleValuation(
  make: string,
  model: string,
  year: number,
  mileage: number,
  condition: string
): Promise<ValuationResult> {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) {
    console.warn("GEMINI_API_KEY not defined inside valuation. Utilizing fallback.");
    return getFallbackValuation(make, model, year, mileage, condition);
  }

  const prompt = `
    As an expert automotive valuer in Pakistan, estimate the current market value of the following vehicle:
    Make: ${make}
    Model: ${model}
    Year: ${year}
    Mileage: ${mileage} km
    Condition: ${condition}
    
    Provide the valuation in Pakistani Rupees (PKR).
    Consider current market trends, inflation, and demand for this specific model in Pakistan.
  `;

  try {
    const response = await ai.models.generateContent({
      model: "gemini-3.5-flash",
      contents: prompt,
      config: {
        responseMimeType: "application/json",
        responseSchema: {
          type: Type.OBJECT,
          properties: {
            estimatedValue: { type: Type.NUMBER, description: "The estimated market value in PKR" },
            marketRange: {
              type: Type.OBJECT,
              properties: {
                low: { type: Type.NUMBER },
                high: { type: Type.NUMBER },
              },
              required: ["low", "high"],
            },
            confidence: { type: Type.NUMBER, description: "Confidence score from 0 to 1" },
            analysis: { type: Type.STRING, description: "Brief analysis of the valuation" },
          },
          required: ["estimatedValue", "marketRange", "confidence", "analysis"],
        },
      },
    });

    return JSON.parse(response.text);
  } catch (err) {
    console.error("Valuation API error or Rate limit hit, falling back to local engine:", err);
    return getFallbackValuation(make, model, year, mileage, condition);
  }
}
